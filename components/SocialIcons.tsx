const ORDER: Key[] = [
  "facebook",
  "x",
  "instagram",
  "youtube",
  "linkedin",
  "tiktok",
  "whatsapp",
];

export default function SocialIcons({
  variant = "dark",
  size = "md",
  keys,
  className,
  withLabels = false,
}: {
  /** dark = rendered on navy/dark backgrounds; light = on white backgrounds */
  variant?: "dark" | "light";
  size?: "xs" | "sm" | "md";
  keys?: Key[];
  className?: string;
  withLabels?: boolean;
}) {
  const list = keys ?? ORDER;
  return (
    <ul className={cn("flex flex-wrap items-center gap-2", className)}>
      {list.map((key) => {
        const meta = META[key];
        const box =
          size === "xs"
            ? "h-7 w-7"
            : size === "sm"
              ? "h-8 w-8"
              : "h-9 w-9";
        const icon =
          size === "xs"
            ? "h-3.5 w-3.5"
            : size === "sm"
              ? "h-[15px] w-[15px]"
              : "h-[17px] w-[17px]";
        const base =
          "group/soc flex items-center justify-center rounded-full transition-all duration-200 hover:bg-[var(--brand)] hover:text-white hover:scale-110";
        const tone =
          variant === "dark"
            ? "bg-white/10 text-white/80"
            : "bg-slate-100 text-slate-600";
        return (
          <li key={key} className="flex items-center">
            <a
              href={SITE.social[key]}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={`${SITE.name} on ${meta.label}`}
              title={`Follow 180 Degrees News on ${meta.label}`}
              className={cn(base, tone, box)}
              style={{ ["--brand" as string]: meta.brand }}
            >
              <svg viewBox="0 0 24 24" fill="currentColor" className={icon} aria-hidden="true">
                <path d={meta.path} />
              </svg>
            </a>
            {withLabels && (
              <span className="ml-2 mr-2 text-xs font-semibold opacity-80">
                {meta.label}
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}
